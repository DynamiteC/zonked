#!/usr/bin/env node
// Turns the record of a real verify:all run (.work/verify-results.json) into docs/RUN-RESULTS.md,
// and fills the block between the counts markers in README.md and app/README.md.
//   node scripts/update-counts.mjs
// A README that still has the PLACEHOLDER-FINAL-RUN line gets the marker block in its place.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const START = '<!-- counts:start -->';
export const END = '<!-- counts:end -->';
const PLACEHOLDER = /^.*PLACEHOLDER-FINAL-RUN.*$/m;

const n = (v) => (Number.isFinite(v) ? String(v) : 'not parsed');

/** Matrix numbers come from the matrix run itself. */
export function matrixCounts(results) {
  if (!Array.isArray(results)) return null;
  const rows = results.flatMap((c) => c.results ?? []);
  return { passed: rows.filter((r) => r.ok).length, total: rows.length, combos: results.length };
}

export function renderBlock(rec, matrix) {
  const c = rec.counts ?? {};
  const e2e = c['verify-e2e'] ?? {};
  const lines = [
    START,
    `Numbers from one verify:all run on commit \`${rec.commit.slice(0, 12)}\` (${rec.date.slice(0, 10)}). Generated by \`scripts/update-counts.mjs\`, do not edit by hand.`,
    '',
    `- Rust DSP tests: ${n(c['cargo-test'])}`,
    `- Web unit tests (Vitest): ${n(c.vitest?.tests)} in ${n(c.vitest?.files)} files. Some of these stub the audio engine (labelled mocked in their file names or headers).`,
    `- Crew bridge tests: ${n(c['bridge-tests'])}`,
    `- App backend tests: ${n(c['app-backend-tests'])}`,
    `- Script tests: ${n(c['web-script-tests'] + c['root-script-tests'])}`,
    `- Real browser checks (Playwright, Chromium, real audio engine): ${n(e2e.passed)} of ${n(e2e.total)}`,
    matrix === null ? '- Browser matrix: not run' : `- Browser matrix (Chromium, Firefox, WebKit builds from Playwright, ${matrix.combos} combinations): ${matrix.passed} of ${matrix.total} checks`,
    END,
  ];
  return lines.join('\n');
}

export function splice(text, block) {
  if (text.includes(START) && text.includes(END)) return text.replace(new RegExp(`${START}[\\s\\S]*?${END}`), () => block);
  if (PLACEHOLDER.test(text)) return text.replace(PLACEHOLDER, () => block);
  return text;
}

function main() {
  const file = join(ROOT, '.work', 'verify-results.json');
  if (!existsSync(file)) {
    console.error('no .work/verify-results.json: run npm run verify:all first (a full run, no VERIFY_ONLY or VERIFY_SKIP)');
    process.exit(1);
  }
  const rec = JSON.parse(readFileSync(file, 'utf8'));
  const mfile = join(ROOT, '.work', 'matrix', 'results.json');
  const matrix = existsSync(mfile) ? matrixCounts(JSON.parse(readFileSync(mfile, 'utf8'))) : null;
  const block = renderBlock(rec, matrix);
  writeFileSync(join(ROOT, 'docs', 'RUN-RESULTS.md'), `# Run results\n\n${block}\n`);
  for (const f of ['README.md', 'app/README.md']) {
    const p = join(ROOT, f);
    if (!existsSync(p)) continue;
    const before = readFileSync(p, 'utf8');
    const after = splice(before, block);
    if (after !== before) writeFileSync(p, after);
    console.log(`${f}: ${after === before ? 'no markers, left alone' : 'counts block written'}`);
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
